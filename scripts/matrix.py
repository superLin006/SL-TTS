def _pick(seq, i):
    return seq[i % len(seq)]


def make_spec(index):
    tone = _pick(TONES, index * 11)
    common = {
        "id": f"v2_{index:04d}",
        "functions": [FUNCTIONS[(index * 5 + k) % len(FUNCTIONS)] for k in range(4)],
        "tone": tone,
        "seed": random.Random(index * 7919).random(),
    }

    if index < 120:
        name, relations, goals = _pick(SCENES, index)
        groups = []
        for j in range(3):
            rel = relations[(index + j) % len(relations)]
            goal = goals[(index * 2 + j) % len(goals)] if j % 2 == 0 else SUBGOALS[(index * 3 + j) % len(SUBGOALS)]
            groups.append({"relation": rel, "goal": goal})
        return {**common, "kind": "scene", "scene": name, "groups": groups,
                "numbers": [NUMBERS[(index * 13 + k) % len(NUMBERS)] for k in range(2)],
                "poly": POLY[(index * 7) % len(POLY)], "english": False,
                "length": (25, 45, 30), "n_dialogues": 8}

    if index < 153:
        ntype = NUMBERS[index - 120]
        situations = NUMBER_SCENES[ntype]
        groups = [{"relation": ["朋友", "同事", "家人", "店员与顾客", "邻居"][(index + j) % 5],
                   "goal": f"围绕“{situations[j]}”展开，必须自然说出一个{ntype}"} for j in range(3)]
        return {**common, "kind": "numbers", "scene": "、".join(situations),
                "focus_number": ntype, "groups": groups,
                "numbers": [ntype], "poly": POLY[(index * 5) % len(POLY)], "english": False,
                "length": (35, 45, 20), "n_dialogues": 8}

    if index < 186:
        k = index - 153
        group_idx = k // 2 if k < 16 else 8 + (k - 16)
        poly = POLY[group_idx]
        situations = POLY_SCENES[poly[0]].split("、")
        groups = [{"relation": ["朋友", "同事", "家人", "店员与顾客", "邻居"][(index + j) % 5],
                   "goal": f"围绕“{situations[j % len(situations)]}”展开，必须自然用上含“{poly[0]}”的词"} for j in range(3)]
        return {**common, "kind": "poly", "scene": POLY_SCENES[poly[0]], "groups": groups,
                "numbers": [NUMBERS[(index * 13) % len(NUMBERS)]],
                "poly": poly, "english": False, "length": (25, 45, 30), "n_dialogues": 8}

    if index < 206:
        m = index - 186
        name, relations, goals = MIXED_SCENES[m % len(MIXED_SCENES)]
        groups = [{"relation": relations[(m + j) % len(relations)],
                   "goal": goals[(m + j) % len(goals)]} for j in range(3)]
        pool = [ENGLISH_TERMS[(m * 5 + k) % len(ENGLISH_TERMS)] for k in range(5)]
        return {**common, "kind": "mixed", "scene": name, "groups": groups,
                "english_pool": pool,
                "numbers": [NUMBERS[(index * 13 + k) % len(NUMBERS)] for k in range(2)],
                "poly": POLY[(index * 3) % len(POLY)], "english": True,
                "length": (25, 45, 30), "n_dialogues": 8}

    name, relations, goals = _pick(SCENES, index * 9)
    groups = [{"relation": relations[(index + j) % len(relations)],
               "goal": goals[(index + j) % len(goals)]} for j in range(3)]
    return {**common, "kind": "long", "scene": name, "groups": groups,
            "numbers": [NUMBERS[(index * 17 + k) % len(NUMBERS)] for k in range(2)],
            "poly": POLY[(index * 9) % len(POLY)], "english": False,
            "length": (5, 25, 70), "n_dialogues": 6}
